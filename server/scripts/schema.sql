CREATE TABLE IF NOT EXISTS "Movie" (
  m_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  m_name VARCHAR(255) NOT NULL,
  release_date DATE,
  director VARCHAR(255),
  actors TEXT,
  poster_url TEXT,
  trailer_url TEXT,
  description TEXT,
  duration_minutes INTEGER,
  language VARCHAR(64),
  rating VARCHAR(32),
  genre VARCHAR(64)
);

ALTER TABLE "Movie" ADD COLUMN IF NOT EXISTS genre VARCHAR(64);

CREATE TABLE IF NOT EXISTS "Theatre" (
  t_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  t_name VARCHAR(255) NOT NULL,
  location VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS "Admin" (
  admin_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  password VARCHAR(255) NOT NULL,
  salary NUMERIC(10,2) DEFAULT 0
);

CREATE TABLE IF NOT EXISTS "Customer" (
  c_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  c_name VARCHAR(255),
  email_id VARCHAR(255) UNIQUE,
  phone_no VARCHAR(32),
  password VARCHAR(255),
  dob DATE
);

CREATE TABLE IF NOT EXISTS "Shows" (
  show_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  st_time VARCHAR(32),
  end_time VARCHAR(32),
  language VARCHAR(64),
  duration_weeks INTEGER,
  m_id INTEGER,
  t_id INTEGER
);

CREATE TABLE IF NOT EXISTS "Tickets" (
  ticket_no INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  show_id INTEGER,
  show_date DATE,
  show_time VARCHAR(32),
  seat_no VARCHAR(16),
  seat_label VARCHAR(16),
  hall_no INTEGER,
  t_id INTEGER,
  price NUMERIC(10,2),
  admin_id INTEGER
);

CREATE TABLE IF NOT EXISTS "Booking" (
  booking_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  ticket_no INTEGER,
  c_id INTEGER,
  total_price NUMERIC(10,2) DEFAULT 0,
  offer_id INTEGER
);

CREATE TABLE IF NOT EXISTS "Seats" (
  seat_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  seat_name VARCHAR(64),
  no_of_seats INTEGER,
  t_id INTEGER
);

CREATE TABLE IF NOT EXISTS "Discount" (
  offer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  m_name VARCHAR(255),
  price NUMERIC(10,2)
);

CREATE TABLE IF NOT EXISTS distributed_booking_metadata (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id INTEGER NOT NULL,
  node_id INTEGER NOT NULL,
  node_role VARCHAR(32) NOT NULL,
  distributed_timestamp VARCHAR(64) NOT NULL,
  coordinator_id INTEGER,
  replication_status VARCHAR(32) DEFAULT 'PENDING',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS idempotency_keys (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  idempotency_key VARCHAR(128) NOT NULL UNIQUE,
  booking_id INTEGER,
  response_body TEXT,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS replicated_bookings (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_booking_id INTEGER NOT NULL UNIQUE,
  customer_id INTEGER NOT NULL,
  show_id INTEGER NOT NULL,
  ticket_no INTEGER,
  seat_data TEXT NOT NULL,
  total_price NUMERIC(10,2) NOT NULL DEFAULT 0,
  source_node_id INTEGER NOT NULL,
  version INTEGER NOT NULL DEFAULT 1,
  event_type VARCHAR(32) NOT NULL DEFAULT 'BOOKING_CREATED',
  event_timestamp VARCHAR(64) NOT NULL,
  replicated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS replication_log (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sequence_no INTEGER NOT NULL DEFAULT 1,
  source_node_id INTEGER NOT NULL,
  destination_node_id INTEGER NOT NULL,
  entity_type VARCHAR(64) NOT NULL,
  entity_id INTEGER NOT NULL,
  operation VARCHAR(32) NOT NULL,
  version INTEGER NOT NULL DEFAULT 1,
  status VARCHAR(32) NOT NULL,
  error_message TEXT,
  timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS server_state (
  node_id INTEGER PRIMARY KEY,
  role VARCHAR(32) NOT NULL,
  host VARCHAR(64) NOT NULL,
  port INTEGER NOT NULL,
  status VARCHAR(32) NOT NULL,
  current_coordinator INTEGER,
  is_primary BOOLEAN DEFAULT FALSE,
  last_heartbeat TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  last_replication_at TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS election_log (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  algorithm VARCHAR(32) NOT NULL,
  initiator_node_id INTEGER NOT NULL,
  elected_coordinator_id INTEGER NOT NULL,
  messages_flow TEXT NOT NULL,
  participating_nodes VARCHAR(255) NOT NULL,
  timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS clock_sync_log (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  coordinator_id INTEGER NOT NULL,
  participating_nodes TEXT NOT NULL,
  collected_clocks TEXT NOT NULL,
  adjustments TEXT NOT NULL,
  timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS distributed_request_log (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id VARCHAR(64) NOT NULL,
  client_ip VARCHAR(64) NOT NULL,
  http_method VARCHAR(16) NOT NULL,
  endpoint VARCHAR(255) NOT NULL,
  server_id INTEGER NOT NULL,
  rpc_method VARCHAR(64),
  duration_ms INTEGER NOT NULL,
  status_code INTEGER NOT NULL,
  success BOOLEAN NOT NULL DEFAULT TRUE,
  timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS consistency_ledger (
  record_key VARCHAR(128) PRIMARY KEY,
  record_value TEXT NOT NULL,
  version INTEGER NOT NULL,
  written_by_node INTEGER NOT NULL,
  write_mode VARCHAR(32) NOT NULL,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS consistency_replica (
  record_key VARCHAR(128) PRIMARY KEY,
  record_value TEXT NOT NULL,
  version INTEGER NOT NULL,
  written_by_node INTEGER NOT NULL,
  replicated_by_node INTEGER NOT NULL,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
