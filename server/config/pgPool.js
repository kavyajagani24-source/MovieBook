import pg from "pg";
import dotenv from "dotenv";

dotenv.config();

// Inside Docker, the mounted .env says localhost. That reaches the container, not Postgres on Windows.
if (process.env.RUNTIME === "docker") {
  process.env.DB_HOST = process.env.DB_HOST_DOCKER || "host.docker.internal";
}

const { Pool } = pg;

const pool = new Pool({
  host: process.env.DB_HOST || "localhost",
  port: Number(process.env.DB_PORT || 5432),
  user: process.env.DB_USER || "postgres",
  password: process.env.DB_PASSWORD || "",
  database: process.env.DB_NAME || "postgres",
  max: 10
});

const ID_COLUMNS = [
  "ticket_no",
  "booking_id",
  "m_id",
  "c_id",
  "show_id",
  "t_id",
  "offer_id",
  "seat_id",
  "admin_id",
  "id"
];

export function translateSql(sql) {
  let text = String(sql);
  text = text.replace(/`([^`]+)`/g, '"$1"');
  text = text.replace(/\s+ENGINE\s*=\s*\w+/gi, "");
  text = text.replace(/\s+ON UPDATE CURRENT_TIMESTAMP/gi, "");
  text = text.replace(/\bAUTO_INCREMENT\b/gi, "GENERATED BY DEFAULT AS IDENTITY");
  text = text.replace(/CURRENT_DATE\(\)/gi, "CURRENT_DATE");
  let index = 0;
  text = text.replace(/\?/g, () => `$${++index}`);
  if (/^\s*insert\b/i.test(text) && !/\breturning\b/i.test(text)) {
    text += " RETURNING *";
  }
  return text;
}

function insertIdFrom(row) {
  if (!row) return 0;
  for (const key of ID_COLUMNS) {
    if (row[key] != null) return Number(row[key]);
  }
  return 0;
}

async function run(client, sql, params = []) {
  const text = translateSql(sql);
  const result = await client.query(text, params);
  if (result.command === "SELECT" || result.command === "SHOW") {
    return [result.rows, result];
  }
  const header = {
    insertId: insertIdFrom(result.rows?.[0]),
    affectedRows: result.rowCount || 0,
    rowCount: result.rowCount || 0,
    rows: result.rows || []
  };
  return [header, result];
}

const api = {
  query: (sql, params) => run(pool, sql, params),
  async getConnection() {
    const client = await pool.connect();
    return {
      query: (sql, params) => run(client, sql, params),
      beginTransaction: () => client.query("BEGIN"),
      commit: () => client.query("COMMIT"),
      rollback: () => client.query("ROLLBACK").catch(() => {}),
      release: () => client.release()
    };
  }
};

const db = {
  promise: () => api
};

export { pool };
export default db;
